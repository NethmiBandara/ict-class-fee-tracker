import { DatabaseSync } from "node:sqlite";
import postgres from "postgres";

const sourcePath = process.argv[2];
const url = process.env.SUPABASE_DATABASE_URL || "";

if (!sourcePath) {
  throw new Error("Pass the sqlite backup path.");
}
if (!/^postgres(ql)?:\/\//i.test(url)) {
  throw new Error("Set SUPABASE_DATABASE_URL to the Supabase Postgres connection string.");
}

function redact(error) {
  const message = error instanceof Error ? error.message : String(error);
  return message.replace(/postgres(?:ql)?:\/\/\S+/gi, "postgresql://***");
}

const sqlite = new DatabaseSync(sourcePath, { readOnly: true });

function rows(sql) {
  return sqlite.prepare(sql).all();
}

function count(table) {
  return Number(sqlite.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n || 0);
}

const source = {
  classes: count("classes"),
  students: count("students"),
  payments: count("payments"),
  attendance: count("attendance"),
  holidays: count("class_holidays"),
};

if (
  source.classes < 10 ||
  source.students < 37 ||
  source.payments < 24 ||
  source.attendance < 148 ||
  source.holidays < 1
) {
  throw new Error(
    `Refusing to copy a smaller database: ${JSON.stringify(source)}`,
  );
}

const holidayCols = sqlite
  .prepare("PRAGMA table_info(class_holidays)")
  .all()
  .map((col) => col.name);

const sql = postgres(url, {
  prepare: false,
  ssl: "require",
  max: 1,
  idle_timeout: 20,
  connect_timeout: 20,
});

const schema = `
  CREATE TABLE IF NOT EXISTS classes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    monthly_fee INTEGER NOT NULL DEFAULT 0 CHECK (monthly_fee >= 0),
    billing_period TEXT NOT NULL DEFAULT 'monthly' CHECK (billing_period IN ('monthly', 'weekly', 'daily')),
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('Asia/Colombo', clock_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
  );
  CREATE TABLE IF NOT EXISTS students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    phone TEXT,
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('Asia/Colombo', clock_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
  );
  CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    student_name TEXT NOT NULL DEFAULT '',
    year INTEGER NOT NULL CHECK (year >= 2000),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    week INTEGER NOT NULL DEFAULT 0 CHECK (week BETWEEN 0 AND 53),
    slot INTEGER NOT NULL DEFAULT 0 CHECK (slot >= 0),
    amount INTEGER NOT NULL CHECK (amount >= 0),
    paid_on TEXT NOT NULL DEFAULT (to_char(timezone('Asia/Colombo', clock_timestamp()), 'YYYY-MM-DD')),
    note TEXT,
    UNIQUE (student_id, year, month, week, slot)
  );
  CREATE TABLE IF NOT EXISTS attendance (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    year INTEGER NOT NULL CHECK (year >= 2000),
    week INTEGER NOT NULL CHECK (week BETWEEN 1 AND 53),
    attended INTEGER NOT NULL DEFAULT 1 CHECK (attended IN (0, 1)),
    attended_on TEXT NOT NULL,
    UNIQUE (student_id, attended_on)
  );
  CREATE TABLE IF NOT EXISTS class_holidays (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    year INTEGER NOT NULL CHECK (year >= 2000),
    week INTEGER NOT NULL CHECK (week BETWEEN 1 AND 53),
    holiday_on TEXT,
    note TEXT,
    UNIQUE (class_id, holiday_on)
  );
  CREATE INDEX IF NOT EXISTS idx_students_class ON students(class_id);
  CREATE INDEX IF NOT EXISTS idx_payments_period ON payments(year, month, week);
  CREATE INDEX IF NOT EXISTS idx_payments_student ON payments(student_id);
  CREATE INDEX IF NOT EXISTS idx_attendance_week ON attendance(year, week);
  CREATE INDEX IF NOT EXISTS idx_attendance_student ON attendance(student_id);
  CREATE INDEX IF NOT EXISTS idx_attendance_day ON attendance(attended_on);
  CREATE UNIQUE INDEX IF NOT EXISTS idx_class_holidays_legacy_week
    ON class_holidays(class_id, year, week) WHERE holiday_on IS NULL;
  CREATE INDEX IF NOT EXISTS idx_class_holidays_week ON class_holidays(class_id, year, week);
  CREATE INDEX IF NOT EXISTS idx_class_holidays_day ON class_holidays(class_id, holiday_on);
`;

try {
  for (const statement of schema.split(";").map((part) => part.trim()).filter(Boolean)) {
    await sql.unsafe(statement);
  }

  const existing = Number(
    (await sql`SELECT COUNT(*) AS n FROM students`)[0].n || 0,
  );
  if (existing > 0) {
    const target = {
      classes: Number((await sql`SELECT COUNT(*) AS n FROM classes`)[0].n || 0),
      students: existing,
      payments: Number((await sql`SELECT COUNT(*) AS n FROM payments`)[0].n || 0),
      attendance: Number((await sql`SELECT COUNT(*) AS n FROM attendance`)[0].n || 0),
      holidays: Number((await sql`SELECT COUNT(*) AS n FROM class_holidays`)[0].n || 0),
    };
    console.log(`already-present ${JSON.stringify(target)}`);
    if (
      target.classes < source.classes ||
      target.students < source.students ||
      target.payments < source.payments ||
      target.attendance < source.attendance ||
      target.holidays < source.holidays
    ) {
      throw new Error("Supabase already has rows and they do not cover the backup.");
    }
    process.exit(0);
  }

  const classes = rows(
    "SELECT id, name, monthly_fee, billing_period, created_at FROM classes ORDER BY id",
  );
  const students = rows(
    "SELECT id, class_id, name, phone, active, created_at FROM students ORDER BY id",
  );
  const payments = rows(
    "SELECT id, student_id, student_name, year, month, week, slot, amount, paid_on, note FROM payments ORDER BY id",
  );
  const attendance = rows(
    "SELECT id, student_id, year, week, attended, attended_on FROM attendance ORDER BY id",
  );
  const holidays = rows(
    holidayCols.includes("holiday_on")
      ? "SELECT id, class_id, year, week, holiday_on, note FROM class_holidays ORDER BY id"
      : "SELECT id, class_id, year, week, NULL AS holiday_on, note FROM class_holidays ORDER BY id",
  );

  await sql.begin(async (tx) => {
    for (const row of classes) {
      await tx`INSERT INTO classes (id, name, monthly_fee, billing_period, created_at)
        VALUES (${row.id}, ${row.name}, ${row.monthly_fee}, ${row.billing_period}, ${row.created_at})`;
    }
    for (const row of students) {
      await tx`INSERT INTO students (id, class_id, name, phone, active, created_at)
        VALUES (${row.id}, ${row.class_id}, ${row.name}, ${row.phone}, ${row.active}, ${row.created_at})`;
    }
    for (const row of payments) {
      await tx`INSERT INTO payments (id, student_id, student_name, year, month, week, slot, amount, paid_on, note)
        VALUES (${row.id}, ${row.student_id}, ${row.student_name}, ${row.year}, ${row.month}, ${row.week}, ${row.slot}, ${row.amount}, ${row.paid_on}, ${row.note})`;
    }
    for (const row of attendance) {
      await tx`INSERT INTO attendance (id, student_id, year, week, attended, attended_on)
        VALUES (${row.id}, ${row.student_id}, ${row.year}, ${row.week}, ${row.attended}, ${row.attended_on})`;
    }
    for (const row of holidays) {
      await tx`INSERT INTO class_holidays (id, class_id, year, week, holiday_on, note)
        VALUES (${row.id}, ${row.class_id}, ${row.year}, ${row.week}, ${row.holiday_on}, ${row.note})`;
    }
    for (const table of ["classes", "students", "payments", "attendance", "class_holidays"]) {
      await tx.unsafe(
        `SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST((SELECT COALESCE(MAX(id), 1) FROM ${table}), 1), true)`,
      );
    }
  });

  const copied = {
    classes: Number((await sql`SELECT COUNT(*) AS n FROM classes`)[0].n || 0),
    students: Number((await sql`SELECT COUNT(*) AS n FROM students`)[0].n || 0),
    payments: Number((await sql`SELECT COUNT(*) AS n FROM payments`)[0].n || 0),
    attendance: Number((await sql`SELECT COUNT(*) AS n FROM attendance`)[0].n || 0),
    holidays: Number((await sql`SELECT COUNT(*) AS n FROM class_holidays`)[0].n || 0),
  };
  console.log(`copied ${JSON.stringify(copied)}`);
  if (
    copied.classes < source.classes ||
    copied.students < source.students ||
    copied.payments < source.payments ||
    copied.attendance < source.attendance ||
    copied.holidays < source.holidays
  ) {
    throw new Error(`Copy finished short: ${JSON.stringify(copied)}`);
  }
} catch (error) {
  console.error(redact(error));
  process.exitCode = 1;
} finally {
  await sql.end({ timeout: 5 });
}
